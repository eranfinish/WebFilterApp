#!/usr/bin/env node
// Regenerates the browser extension's ad-server ruleset (extension/rulesets/ads.json and its licence notice,
// docs/PROTECTION-SPEC.md §12) from the pinned EasyList commit in sources.mjs. Run by hand, then review the diff:
//
//   node tools/starter-lists/ad-ruleset.mjs [--cache-dir <dir>] [--offline] [--report <file>]
//
// Downloads go to the same cache as update.mjs (default: <os tmp>/webfilter-starter-lists) and are only parsed as text;
// the review report goes to review-ads.txt there. The rules come from ad-rules.mjs (unit-tested by the extension).
// No dependencies; Node 20 or later.

import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import zlib from "node:zlib";
import * as curation from "./curation.mjs";
import { buildAdRuleset, formatRuleset, parseBlockRules, parseExceptions } from "./ad-rules.mjs";
import { CRUX_MONTH, CRUX_SOURCES, EASYLIST, PSL_SOURCE, commandLine, download, easylist, parseCrux, parsePsl } from "./sources.mjs";

const here = path.dirname(url.fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const listsDir = path.join(repoRoot, "data", "starter-lists");
const rulesetsDir = path.join(repoRoot, "extension", "rulesets");

/** EasyList's ad-server list and the whole-domain rules of its third-party list; exceptions from its allowlist. */
const SOURCES = {
  adservers: easylist("easylist_adservers.txt"),
  thirdparty: easylist("easylist_thirdparty.txt"),
  allowlist: easylist("easylist_allowlist.txt"),
  psl: PSL_SOURCE,
  ...CRUX_SOURCES,
};

const cli = commandLine(process.argv.slice(2), "review-ads.txt");
const data = {};
for (const [name, source] of Object.entries(SOURCES)) data[name] = await download(name, source, cli);
const text = (name) => data[name].toString("utf8");

// ---- inputs ---------------------------------------------------------------------------------------------------------

const adservers = parseBlockRules(text("adservers"));
const thirdparty = parseBlockRules(text("thirdparty"));
const { exceptions, skipped: skippedExceptions } = parseExceptions(text("allowlist"));
const allowListDomains = curation.ALLOW_LISTS.flatMap((name) => JSON.parse(fs.readFileSync(path.join(listsDir, `${name}.json`), "utf8")).domains);

const { rules, report } = buildAdRuleset([...adservers.rules, ...thirdparty.rules], exceptions, {
  isPublicSuffix: parsePsl(data.psl),
  protectTree: [...curation.AD_ESSENTIALS, ...allowListDomains],
  protectSelfAndParents: curation.NEVER_BLOCK,
  remove: curation.AD_SERVERS.remove,
});

// ---- output ---------------------------------------------------------------------------------------------------------

const json = formatRuleset(rules);
const domains = report.domains.any + report.domains.thirdParty;
fs.writeFileSync(path.join(rulesetsDir, "ads.json"), json);
fs.writeFileSync(
  path.join(rulesetsDir, "ads-notice.txt"),
  `WebFilter ad-server ruleset (rulesets/ads.json)

Contains material from EasyList (https://easylist.to/), by the EasyList authors, dual licensed under the GNU General
Public License version 3 or later and the Creative Commons Attribution-ShareAlike 3.0 Unported License or later
(https://easylist.to/pages/licence.html). rulesets/ads.json is an adaptation used and licensed under the Creative Commons
Attribution-ShareAlike 4.0 International License (https://creativecommons.org/licenses/by-sa/4.0/).
Attribution: The EasyList authors (https://easylist.to/).

Source: github.com/easylist/easylist, commit ${EASYLIST}: easylist/easylist_adservers.txt and
easylist/easylist_thirdparty.txt (blocking rules), easylist/easylist_allowlist.txt (exceptions).

Changes: only whole-domain rules ("||domain^", "||domain^$third-party") were kept, as declarativeNetRequest block rules
for every request type except page loads; exceptions for a host were applied to the whole host on the sites they name;
domains of major platforms, of sign-in and school services, and public suffixes were left out. Generated by
tools/starter-lists/ad-ruleset.mjs in the WebFilter repository: ${domains} domains in ${rules.length} rules.

The material is provided as is, without warranties of any kind.
`,
);

// ---- review report --------------------------------------------------------------------------------------------------

const ranks = new Map();
parseCrux(data.cruxGlobal, ranks);
parseCrux(data.cruxIsrael, ranks);
const anyParty = rules.filter((r) => !r.condition.domainType).flatMap((r) => r.condition.requestDomains);
const visited = anyParty.filter((d) => ranks.has(d)).sort((a, b) => ranks.get(a) - ranks.get(b));
const belowPlatforms = rules
  .flatMap((r) => r.condition.requestDomains.map((d) => `${d}${r.condition.domainType ? "($3p)" : ""}`))
  .filter((d) => curation.NEVER_BLOCK.some((p) => d.replace(/\(\$3p\)$/, "").endsWith("." + p)))
  .sort();
const lines = [
  `EasyList ${EASYLIST}`,
  `easylist_adservers.txt: ${adservers.rules.length} whole-domain rules, ${adservers.skipped} other rules skipped`,
  `easylist_thirdparty.txt: ${thirdparty.rules.length} whole-domain rules, ${thirdparty.skipped} other rules skipped`,
  `easylist_allowlist.txt: ${exceptions.length} host exceptions, ${skippedExceptions.length} with a host this tool cannot read: ${skippedExceptions.join("  ") || "none"}`,
  "",
  `ruleset: ${rules.length} rules, ${report.domains.any} any-party and ${report.domains.thirdParty} third-party domains, ${json.length} bytes (${zlib.gzipSync(json).length} gzipped)`,
  `subdomains of a listed domain dropped: ${report.covered}`,
  `public suffixes dropped: ${report.publicSuffix.join(" ") || "none"}`,
  `protected (essentials, allow lists, platforms) dropped: ${report.protected.join(" ") || "none"}`,
  `curated removals hit: ${report.removed.join(" ") || "none"}`,
  `spared on every site by an exception: ${report.exemptEverywhere.join(" ") || "none"}`,
  "spared on some sites by an exception (own rule with excludedInitiatorDomains):",
  ...report.exemptOnSites.map((e) => `  ${e.host}: ${e.sites.join(" ")}`),
  "",
  `kept below a platform of NEVER_BLOCK (one site's or one service's host; review): ${belowPlatforms.join(" ") || "none"}`,
  "",
  `blocked for any party and visited as pages (CrUX ${CRUX_MONTH}, global and Israel; their own pages lose these hosts' scripts`,
  "and images — review for false positives, most visited first):",
];
for (let i = 0; i < visited.length; i += 8) lines.push("  " + visited.slice(i, i + 8).map((d) => `${d}(${ranks.get(d) / 1000}k)`).join(" "));
fs.mkdirSync(path.dirname(cli.reportFile), { recursive: true });
fs.writeFileSync(cli.reportFile, lines.join("\n") + "\n");

console.log(`wrote extension/rulesets/ads.json: ${domains} domains in ${rules.length} rules, ${json.length} bytes (${zlib.gzipSync(json).length} gzipped)`);
console.log(`review report: ${cli.reportFile}`);
